# ── Helpers ───────────────────────────────────────────────────────────────────


def write_json(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        json.dump(data, f, indent=2)
        f.write("\n")


def build_name_text(r):
    prefix_str = (r["prefix"][0] + " ") if r["prefix"] else ""
    return f"{prefix_str}{r['first_name']} {r['middle_name']} {r['last_name']}"


