# ruff: noqa: E501
"""
Scaffold the standard REST API pattern for a model using a package-based API layout.

Generated API modules are split into ``apis/<resource>/crud.py``, ``history.py``, and ``audit.py``.
Services, selectors, filters, and urls follow the existing scaffold behavior.
"""

import importlib
from pathlib import Path

from django.apps import apps
from django.conf import settings
from django.core.management.base import BaseCommand, CommandError

from core.common.management import scaffold_standard_api_generator as base_gen
from core.common.management import scaffold_standard_api_package_generator as package_gen
from core.common.management import scaffold_standard_serializers_generator as ser_gen


def _resolve_app_label(raw: str) -> str:
    key = raw.strip()
    try:
        return apps.get_app_config(key).label
    except LookupError:
        pass

    lowered = key.lower()
    for app_config in apps.get_app_configs():
        if app_config.label.lower() == lowered:
            return app_config.label

    raise LookupError(key)


class Command(BaseCommand):
    requires_system_checks: list[str] = []

    help = (
        "Generate the standard API scaffold using package-based API modules. "
        "APIs are written under apis/<resource>/ with crud.py, history.py, and audit.py. "
        "History extras and CRUD audit are generated by default. "
        "Example: python manage.py scaffold_standard_api users.User --full"
    )

    def add_arguments(self, parser):
        parser.add_argument(
            "model",
            type=str,
            help=(
                'Target model as "app_label.ModelName" (e.g. users.User). '
                "App label is case-insensitive."
            ),
        )
        parser.add_argument(
            "--url-prefix",
            type=str,
            default=None,
            help="Kebab-case path segment for urls.py (default: slug of Meta.verbose_name_plural).",
        )
        parser.add_argument(
            "--openapi-tag",
            type=str,
            default=None,
            help=('OpenAPI tag string written to constants.py and used in extend_schema (default: "{url-prefix}").'),
        )
        parser.add_argument(
            "--skip-constants",
            action="store_true",
            help="Do not add or merge OpenAPI tag lines in the app's constants.py.",
        )
        parser.add_argument(
            "--dry-run",
            action="store_true",
            help="Print paths that would be written; do not modify files.",
        )
        parser.add_argument(
            "--force",
            action="store_true",
            help="Overwrite generated resource modules if they already exist.",
        )
        parser.add_argument(
            "--skip-filters",
            action="store_true",
            help="Do not write or merge filters.py (use if a FilterSet for this model already exists).",
        )
        parser.add_argument(
            "--skip-urls",
            action="store_true",
            help="Do not write urls.py (use if urlpatterns already exist and you will merge manually).",
        )
        parser.add_argument(
            "--skip-api",
            action="store_true",
            help=(
                "Do not write apis/<resource>/, serializers/<resource>.py, or merge apis or serializers barrel "
                "(services/selectors still generated)."
            ),
        )
        parser.add_argument(
            "--skip-services",
            action="store_true",
            help="Do not write services/<resource>.py or merge services/__init__.py.",
        )
        parser.add_argument(
            "--skip-selectors",
            action="store_true",
            help="Do not write selectors/<resource>.py or merge selectors/__init__.py.",
        )
        parser.add_argument(
            "--full",
            action="store_true",
            help="Shorthand for --rich-serializers (history extras and CRUD audit are already on by default).",
        )
        parser.add_argument(
            "--with-history-extras",
            action="store_true",
            help="Legacy no-op flag. History previous/next, diff, and revert are generated by default.",
        )
        parser.add_argument(
            "--with-crud-audit",
            action="store_true",
            help="Explicitly enable object- and model-scoped CRUD audit list APIs (now on by default).",
        )
        parser.add_argument(
            "--rich-serializers",
            action="store_true",
            help="Use UserCompactSerializer, RevisionSerializer, get_<entity>_detail, compact history list, etc.",
        )
        parser.add_argument(
            "--only-bulk",
            action="store_true",
            help=(
                "Generate only the bulk endpoints. Writes apis/<resource>/bulk.py, "
                "appends the bulk-update item serializer into the existing "
                "serializers/<resource>.py, merges apis + serializers __init__.py, "
                "and injects the bulk url paths into the existing urls.py. "
                "Skips services, selectors, filters, and constants. "
                "When the positional arg is just an app label (no dot), batches "
                "every scaffolded resource in that app (e.g. 'individuals')."
            ),
        )

    def handle(self, *args, **options):
        model_arg: str = options["model"].strip()
        only_bulk: bool = options["only_bulk"]

        if only_bulk and "." not in model_arg:
            self._handle_only_bulk_for_app(
                app_label_raw=model_arg,
                dry_run=options["dry_run"],
                force=options["force"],
            )
            return

        if "." not in model_arg:
            raise CommandError(
                'model must look like "app_label.ModelName" '
                '(or just "app_label" with --only-bulk to batch all resources in the app)'
            )

        app_label_raw, model_name = model_arg.split(".", 1)
        if not app_label_raw or not model_name:
            raise CommandError('model must look like "app_label.ModelName"')

        try:
            app_label = _resolve_app_label(app_label_raw)
        except LookupError as exc:
            raise CommandError(
                f"Unknown app label {app_label_raw!r}. "
                "Use the Django app label (often lowercase), e.g. identities.IdentityGroup."
            ) from exc

        try:
            model_cls = apps.get_model(app_label, model_name)
        except LookupError as exc:
            raise CommandError(
                f"Unknown model {model_arg!r} (resolved app {app_label!r}). "
                "Check spelling and that the model is installed."
            ) from exc

        app_config = apps.get_app_config(app_label)
        models_mod = importlib.import_module(f"{app_config.name}.models")
        if getattr(models_mod, model_name, None) is not model_cls:
            raise CommandError(
                f"Model {model_name} must be exported from {app_config.name}.models "
                "(import it in models/__init__.py if it lives in a submodule)."
            )

        models_file = Path(models_mod.__file__).resolve()
        app_dir = models_file.parent.parent if models_file.name != "models.py" else models_file.parent

        full: bool = options["full"]
        with_history_extras: bool = True
        with_crud_audit: bool = True
        rich_serializers: bool = options["rich_serializers"] or full
        with_filters: bool = not options["skip_filters"]

        try:
            ctx = base_gen.build_context(
                model=model_cls,
                url_prefix=options["url_prefix"],
                openapi_tag=options["openapi_tag"],
                with_history_extras=with_history_extras,
                with_crud_audit=with_crud_audit,
                rich_serializers=rich_serializers,
                with_filters=with_filters,
            )
        except ValueError as exc:
            raise CommandError(str(exc)) from exc

        dry_run: bool = options["dry_run"]
        force: bool = options["force"]
        skip_api: bool = options["skip_api"]
        skip_services: bool = options["skip_services"]
        skip_selectors: bool = options["skip_selectors"]
        only_bulk: bool = options["only_bulk"]

        if only_bulk:
            self._handle_only_bulk(ctx, app_dir=app_dir, dry_run=dry_run, force=force)
            return

        if skip_api and skip_services and skip_selectors:
            raise CommandError(
                "Cannot use --skip-api, --skip-services, and --skip-selectors together (nothing would be generated)."
            )

        self.stdout.write(
            self.style.NOTICE(f"Scaffolding {ctx.app_python_path}.{ctx.model_name} → {ctx.resource_module}")
        )

        if not skip_api:
            self._ensure_package(app_dir, "apis", force)
            self._ensure_package(app_dir, "serializers", force)
        if not skip_services:
            self._ensure_package(app_dir, "services", force)
        if not skip_selectors:
            self._ensure_package(app_dir, "selectors", force)

        constants_path = app_dir / "constants.py"
        if options["skip_constants"]:
            self.stdout.write(self.style.NOTICE("  skip constants.py (--skip-constants)"))
        else:
            self._merge_constants(constants_path, ctx, dry_run=dry_run)

        files = package_gen.collect_generated_files(ctx, app_dir=app_dir)
        api_paths = set(package_gen.api_generated_paths(ctx, app_dir=app_dir))
        services_py = app_dir / "services" / f"{ctx.resource_module}.py"
        selectors_py = app_dir / "selectors" / f"{ctx.resource_module}.py"
        serializers_py = app_dir / "serializers" / f"{ctx.resource_module}.py"

        if skip_api:
            for path in api_paths:
                files.pop(path, None)
            files.pop(serializers_py, None)
            self.stdout.write(self.style.NOTICE("  skip apis + serializers scaffold (--skip-api)"))
        if skip_services:
            files.pop(services_py, None)
            self.stdout.write(self.style.NOTICE("  skip services module (--skip-services)"))
        if skip_selectors:
            files.pop(selectors_py, None)
            self.stdout.write(self.style.NOTICE("  skip selectors module (--skip-selectors)"))

        filters_path = app_dir / "filters.py"
        urls_path = app_dir / "urls.py"
        skip_filters: bool = options["skip_filters"]
        skip_urls: bool = options["skip_urls"]

        for path, content in files.items():
            self._write_text(path, content, dry_run=dry_run, force=force)

        if not skip_api:
            compacts_path = app_dir / "serializers" / "compacts.py"
            self._merge_serializers_compacts(compacts_path, ctx, dry_run=dry_run)

        if skip_filters:
            self.stdout.write(self.style.NOTICE("  skip filters.py (--skip-filters)"))
        else:
            existing_filters = filters_path.read_text() if filters_path.exists() else ""
            try:
                filters_body = (
                    base_gen.merge_filters_py(existing_filters, ctx)
                    if existing_filters.strip()
                    else base_gen.render_filters_py(ctx)
                )
            except ValueError as exc:
                msg = str(exc)
                if "filters.py already defines" in msg and "Filter" in msg:
                    msg += (
                        " Re-run with --skip-filters to regenerate resource modules only, "
                        "or combine with --skip-api / --skip-services / --skip-selectors as needed."
                    )
                raise CommandError(msg) from exc
            self._write_text(
                filters_path,
                filters_body + ("\n" if not filters_body.endswith("\n") else ""),
                dry_run=dry_run,
                force=force,
            )

        if skip_urls:
            self.stdout.write(self.style.NOTICE("  skip urls.py (--skip-urls)"))
        else:
            existing_urls = urls_path.read_text() if urls_path.exists() else ""
            try:
                urls_body = base_gen.merge_urls_py(existing_urls, ctx)
            except ValueError as exc:
                raise CommandError(str(exc)) from exc
            self._write_text(urls_path, urls_body, dry_run=dry_run, force=force)

        entity_snake = base_gen._entity_snake(ctx.model_name)  # noqa: SLF001

        apis_init = app_dir / "apis" / "__init__.py"
        serializers_init = app_dir / "serializers" / "__init__.py"
        services_init = app_dir / "services" / "__init__.py"
        selectors_init = app_dir / "selectors" / "__init__.py"

        if not skip_api:
            self._merge_init(
                apis_init,
                from_module=ctx.resource_module,
                export_names=base_gen.api_export_names(ctx),
                dry_run=dry_run,
            )
            self._merge_init(
                serializers_init,
                from_module="compacts",
                export_names=base_gen.compact_serializer_export_names(ctx),
                dry_run=dry_run,
            )
            self._merge_init(
                serializers_init,
                from_module=ctx.resource_module,
                export_names=base_gen.serializer_export_names(ctx),
                dry_run=dry_run,
            )
        else:
            self.stdout.write(self.style.NOTICE("  skip apis/__init__.py and serializers/__init__.py (--skip-api)"))

        if not skip_services:
            self._merge_init(
                services_init,
                from_module=ctx.resource_module,
                export_names=base_gen.service_export_names(ctx, entity_snake),
                dry_run=dry_run,
            )
        else:
            self.stdout.write(self.style.NOTICE("  skip services/__init__.py merge (--skip-services)"))

        if not skip_selectors:
            selector_exports = base_gen.selector_export_names(ctx, entity_snake, ctx.resource_module)
            self._merge_init(
                selectors_init,
                from_module=ctx.resource_module,
                export_names=selector_exports,
                dry_run=dry_run,
            )
        else:
            self.stdout.write(self.style.NOTICE("  skip selectors/__init__.py merge (--skip-selectors)"))

        mount_hint = (
            f'path("{ctx.app_url_namespace}/", include(("{ctx.app_python_path}.urls", "{ctx.app_url_namespace}"), '
            f'namespace="{ctx.app_url_namespace}")),'
        )
        self.stdout.write("")
        self.stdout.write(self.style.WARNING("Manual steps:"))
        self.stdout.write(f"  1. Mount app urls in core/api/urls.py if needed, e.g.\n       {mount_hint}")
        self.stdout.write(
            "  2. Review serializers (FK UUIDs, ContentType natural keys, DecimalField max_digits/decimal_places vs model, required flags) and service defaults."
        )
        self.stdout.write("  3. Run makemigrations if you changed models; add tests for services/selectors.")
        if dry_run:
            self.stdout.write(self.style.SUCCESS("Dry run complete (no files written)."))
        else:
            self.stdout.write(self.style.SUCCESS("Scaffold complete."))

    def _handle_only_bulk_for_app(self, *, app_label_raw: str, dry_run: bool, force: bool) -> None:
        """Run ``--only-bulk`` for every scaffolded resource inside an app.

        Resources are discovered from ``core/<app>/apis/<resource_module>/crud.py``.
        The model is resolved by canonical name (``Model._meta.model_name``,
        which strips underscores) against the app's installed models, so
        ``practitioner_role`` correctly maps to ``PractitionerRole``.
        """

        try:
            app_label = _resolve_app_label(app_label_raw)
        except LookupError as exc:
            raise CommandError(
                f"Unknown app label {app_label_raw!r}. Use the Django app label, e.g. 'individuals'."
            ) from exc

        app_config = apps.get_app_config(app_label)
        models_mod = importlib.import_module(f"{app_config.name}.models")
        models_file = Path(models_mod.__file__).resolve()
        app_dir = models_file.parent.parent if models_file.name != "models.py" else models_file.parent

        apis_dir = app_dir / "apis"
        if not apis_dir.is_dir():
            raise CommandError(f"{apis_dir} does not exist. Nothing to bulk-scaffold for {app_label}.")

        resource_dirs = sorted(d for d in apis_dir.iterdir() if d.is_dir() and (d / "crud.py").exists())
        if not resource_dirs:
            self.stdout.write(
                self.style.WARNING(
                    f"No scaffolded resources found under {apis_dir.relative_to(Path(settings.BASE_DIR))}"
                )
            )
            return

        model_by_canonical = {model._meta.model_name: model for model in app_config.get_models()}

        self.stdout.write(
            self.style.NOTICE(f"Batch bulk-only scaffold for {app_label}: {len(resource_dirs)} resource(s) discovered")
        )

        processed = 0
        skipped = 0
        failed = 0
        for resource_dir in resource_dirs:
            resource_module = resource_dir.name
            canonical = resource_module.replace("_", "")
            model_cls = model_by_canonical.get(canonical)
            if model_cls is None:
                self.stdout.write(
                    self.style.WARNING(
                        f"  skip {resource_module}: no model with canonical name {canonical!r} in {app_label}"
                    )
                )
                skipped += 1
                continue

            bulk_py = resource_dir / "bulk.py"
            if bulk_py.exists() and not force:
                self.stdout.write(
                    self.style.NOTICE(f"  skip {resource_module}: bulk.py already exists (pass --force to regenerate)")
                )
                skipped += 1
                continue

            if getattr(models_mod, model_cls.__name__, None) is not model_cls:
                self.stdout.write(
                    self.style.WARNING(
                        f"  skip {resource_module}: {model_cls.__name__} not exported from {app_config.name}.models"
                    )
                )
                skipped += 1
                continue

            try:
                ctx = base_gen.build_context(
                    model=model_cls,
                    url_prefix=None,
                    openapi_tag=None,
                    with_history_extras=True,
                    with_crud_audit=True,
                    rich_serializers=False,
                    with_filters=True,
                )
            except ValueError as exc:
                self.stdout.write(self.style.ERROR(f"  skip {resource_module}: {exc}"))
                failed += 1
                continue

            self.stdout.write("")
            try:
                self._handle_only_bulk(ctx, app_dir=app_dir, dry_run=dry_run, force=force, emit_footer=False)
                processed += 1
            except CommandError as exc:
                self.stdout.write(self.style.ERROR(f"  failed {resource_module}: {exc}"))
                failed += 1

        self.stdout.write("")
        summary = f"Batch summary for {app_label}: {processed} processed, {skipped} skipped, {failed} failed"
        if failed:
            self.stdout.write(self.style.ERROR(summary))
        else:
            self.stdout.write(self.style.SUCCESS(summary))
        if processed and not dry_run:
            self.stdout.write("")
            self.stdout.write(self.style.WARNING("Manual steps:"))
            self.stdout.write("  1. Run `make lint` to sort imports in generated files.")
            self.stdout.write("  2. Add Postman folders for the new bulk endpoints.")

    def _handle_only_bulk(
        self,
        ctx,
        *,
        app_dir: Path,
        dry_run: bool,
        force: bool,
        emit_footer: bool = True,
    ) -> None:
        """Generate only the bulk endpoints into an already-scaffolded resource."""

        self.stdout.write(
            self.style.NOTICE(f"Bulk-only scaffold for {ctx.app_python_path}.{ctx.model_name} → {ctx.resource_module}")
        )

        bulk_files = package_gen.collect_bulk_only_files(ctx, app_dir=app_dir)
        if not bulk_files:
            raise CommandError("No bulk classes were generated for this resource. Aborting.")
        for path, content in bulk_files.items():
            self._write_text(path, content, dry_run=dry_run, force=force)

        serializers_py = app_dir / "serializers" / f"{ctx.resource_module}.py"
        if not serializers_py.exists():
            raise CommandError(
                f"{serializers_py.relative_to(Path(settings.BASE_DIR))} does not exist. "
                "Run the full scaffold first, then re-run with --only-bulk."
            )
        existing_serializers = serializers_py.read_text()
        try:
            merged_serializers = ser_gen.merge_bulk_update_item_into_resource_serializers(existing_serializers, ctx)
        except ValueError as exc:
            raise CommandError(str(exc)) from exc
        self._maybe_write_merge(
            serializers_py,
            existing=existing_serializers,
            merged=merged_serializers,
            dry_run=dry_run,
            label="bulk update item serializer",
        )

        urls_py = app_dir / "urls.py"
        if not urls_py.exists():
            raise CommandError(
                f"{urls_py.relative_to(Path(settings.BASE_DIR))} does not exist. "
                "Run the full scaffold first, then re-run with --only-bulk."
            )
        existing_urls = urls_py.read_text()
        try:
            merged_urls = base_gen.merge_bulk_urls_py(existing_urls, ctx)
        except ValueError as exc:
            raise CommandError(str(exc)) from exc
        self._maybe_write_merge(
            urls_py,
            existing=existing_urls,
            merged=merged_urls,
            dry_run=dry_run,
            label="bulk urls",
        )

        apis_init = app_dir / "apis" / ctx.resource_module / "__init__.py"
        self._merge_init(
            apis_init,
            from_module="bulk",
            export_names=base_gen.bulk_api_export_names(ctx),
            dry_run=dry_run,
        )

        serializers_init = app_dir / "serializers" / "__init__.py"
        self._merge_init(
            serializers_init,
            from_module=ctx.resource_module,
            export_names=base_gen.bulk_serializer_export_names(ctx),
            dry_run=dry_run,
        )

        apis_pkg_init = app_dir / "apis" / "__init__.py"
        self._merge_init(
            apis_pkg_init,
            from_module=ctx.resource_module,
            export_names=base_gen.bulk_api_export_names(ctx),
            dry_run=dry_run,
        )

        if emit_footer:
            self.stdout.write("")
            self.stdout.write(self.style.WARNING("Manual steps:"))
            self.stdout.write("  1. Review bulk.py and confirm import order with your linter.")
            self.stdout.write("  2. Add a Postman folder for the bulk-create/update/delete requests.")
            if dry_run:
                self.stdout.write(self.style.SUCCESS("Dry run complete (no files written)."))
            else:
                self.stdout.write(self.style.SUCCESS("Bulk-only scaffold complete."))

    def _maybe_write_merge(
        self,
        path: Path,
        *,
        existing: str,
        merged: str,
        dry_run: bool,
        label: str,
    ) -> None:
        rel = path.relative_to(Path(settings.BASE_DIR))
        if merged.rstrip() == existing.rstrip():
            self.stdout.write(self.style.NOTICE(f"  skip {rel} ({label} already present)"))
            return
        if dry_run:
            self.stdout.write(self.style.NOTICE(f"  would merge {rel} ({label})"))
            return
        out = merged if merged.endswith("\n") else merged + "\n"
        path.write_text(out)
        self.stdout.write(self.style.SUCCESS(f"  merged {rel}"))

    def _merge_constants(self, path: Path, ctx, *, dry_run: bool) -> None:
        existing = path.read_text() if path.exists() else ""
        merged = base_gen.merge_openapi_constant_into_constants(existing, ctx)
        rel = path.relative_to(Path(settings.BASE_DIR))
        if merged.rstrip() == existing.rstrip():
            self.stdout.write(self.style.NOTICE(f"  skip {rel} ({ctx.openapi_tag_constant_name} already defined)"))
            return
        if dry_run:
            self.stdout.write(self.style.NOTICE(f"  would merge {rel} (OpenAPI tag constant)"))
            return
        path.parent.mkdir(parents=True, exist_ok=True)
        out = merged if merged.endswith("\n") else merged + "\n"
        path.write_text(out)
        self.stdout.write(self.style.SUCCESS(f"  merged {rel}"))

    def _merge_serializers_compacts(self, path: Path, ctx, *, dry_run: bool) -> None:
        existing = path.read_text() if path.exists() else ""
        merged = ser_gen.merge_compacts_py(existing, ctx)
        rel = path.relative_to(Path(settings.BASE_DIR))
        if merged.rstrip() == existing.rstrip():
            self.stdout.write(
                self.style.NOTICE(f"  skip {rel} ({ctx.model_name}CompactSerializer already in compacts)")
            )
            return
        if dry_run:
            self.stdout.write(self.style.NOTICE(f"  would merge {rel} (serializers.compacts)"))
            return
        path.parent.mkdir(parents=True, exist_ok=True)
        out = merged if merged.endswith("\n") else merged + "\n"
        path.write_text(out)
        self.stdout.write(self.style.SUCCESS(f"  merged {rel}"))

    def _ensure_package(self, app_dir: Path, name: str, force: bool) -> None:
        pkg = app_dir / name
        single = app_dir / f"{name}.py"
        if pkg.is_dir():
            return
        if single.exists():
            content = single.read_text().strip()
            if content and not force:
                raise CommandError(f"{single} is not empty. Move to {name}/ as a package or pass --force after backup.")
            if content and force:
                raise CommandError(
                    f"Refusing to delete non-empty {single} automatically. "
                    f"Move its contents into {name}/ manually, then re-run."
                )
            single.unlink()
        pkg.mkdir(parents=True, exist_ok=True)
        init = pkg / "__init__.py"
        if not init.exists():
            init.write_text("")

    def _write_text(self, path: Path, content: str, *, dry_run: bool, force: bool) -> None:
        if dry_run:
            self.stdout.write(f"  would write {path.relative_to(Path(settings.BASE_DIR))}")
            return
        if path.exists() and not force:
            if path.name not in {"filters.py", "urls.py", "__init__.py"}:
                raise CommandError(f"File already exists: {path} (use --force to overwrite)")
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        self.stdout.write(self.style.SUCCESS(f"  wrote {path.relative_to(Path(settings.BASE_DIR))}"))

    def _merge_init(
        self,
        path: Path,
        *,
        from_module: str,
        export_names: list[str],
        dry_run: bool,
    ) -> None:
        existing = path.read_text() if path.exists() else ""
        new_content = base_gen.merge_package_init_py(
            existing,
            from_module=from_module,
            export_names=export_names,
        )
        rel = path.relative_to(Path(settings.BASE_DIR))
        if new_content.rstrip() == existing.rstrip():
            self.stdout.write(self.style.NOTICE(f"  skip {rel} (already exports {from_module})"))
            return
        if dry_run:
            self.stdout.write(self.style.NOTICE(f"  would merge {rel}"))
            return
        path.write_text(new_content.rstrip() + "\n")
        self.stdout.write(self.style.SUCCESS(f"  merged {rel}"))
