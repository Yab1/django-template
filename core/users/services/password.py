"""Password change and history (writes)."""

from django.contrib.auth.password_validation import validate_password
from django.contrib.auth.tokens import default_token_generator
from django.core.exceptions import ValidationError
from django.db import transaction
from django.utils.encoding import force_str
from django.utils.http import urlsafe_base64_decode
from django.utils.translation import gettext_lazy as _

from core.users.authz import authorize
from core.users.constants import PASSWORD_HISTORY_LIMIT
from core.users.models import PasswordHistory, User

_INVALID_TOKEN_MSG = _("The password reset link is invalid or has expired.")


def _password_history_trim(*, user: User, keep: int) -> None:
    keep_ids = list(
        PasswordHistory.objects.filter(user=user).order_by("-created_at").values_list("id", flat=True)[:keep]
    )
    if not keep_ids:
        return
    PasswordHistory.objects.filter(user=user).exclude(id__in=keep_ids).delete()


def _apply_password_change(*, user: User, new_password: str) -> None:
    """Validate, archive previous encoded password, persist new hash. Clears must_change_password."""
    validate_password(new_password, user)
    previous_encoded = user.password if user.has_usable_password() else None
    user.set_password(new_password)
    if user.must_change_password:
        user.must_change_password = False
    user.full_clean()
    user.save()
    if previous_encoded:
        PasswordHistory.objects.create(user=user, hashed_password=previous_encoded)
    _password_history_trim(user=user, keep=PASSWORD_HISTORY_LIMIT)


@transaction.atomic
def user_password_change(
    *,
    user: User,
    current_password: str,
    new_password: str,
) -> None:
    """
    Authenticated user changes their own password.

    Raises ``ValidationError`` when the current password is wrong or policy rejects the new password.
    """
    if user.has_usable_password():
        if not user.check_password(current_password):
            raise ValidationError(
                {"current_password": [_("The current password is incorrect.")]},
                code="password_current_incorrect",
            )
    _apply_password_change(user=user, new_password=new_password)


@transaction.atomic
def user_password_reset(
    *,
    target_user: User,
    new_password: str,
    requesting_user: User,
) -> None:
    """
    Set another user's password when ``authorize`` allows ``users:user:password_reset``.

    Archives the previous encoded password so password history cannot be bypassed via this flow.
    """
    authorize(
        user=requesting_user,
        action="users:user:password_reset",
        resource_code="User",
        resource_identifier=str(target_user.id),
    )
    _apply_password_change(user=target_user, new_password=new_password)


@transaction.atomic
def user_password_reset_from_token(
    *,
    uidb64: str,
    token: str,
    new_password: str,
) -> None:
    """
    Validate a one-time password reset token and set a new password.

    Token is generated by Django's ``default_token_generator`` (HMAC, stateless).
    It is automatically invalidated once the password hash changes, so it is
    single-use by construction.

    Clears ``must_change_password`` on success so the user can access all endpoints.

    Raises ``ValidationError`` with code ``invalid_reset_token`` when the uid is
    malformed, the user does not exist, or the token has expired / already been used.
    Also raises ``ValidationError`` when Django's password policy rejects the new value.
    """
    _invalid = ValidationError(
        {"token": [_INVALID_TOKEN_MSG]},
        code="invalid_reset_token",
    )
    try:
        uid = force_str(urlsafe_base64_decode(uidb64))
        user = User.objects.get(pk=uid)
    except (TypeError, ValueError, OverflowError, User.DoesNotExist):
        raise _invalid

    if not default_token_generator.check_token(user, token):
        raise _invalid

    _apply_password_change(user=user, new_password=new_password)
